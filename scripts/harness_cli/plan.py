"""Render plan: every Generated_File the Manifest asks for (agent-harness-platform R6, R7).

``build_plan`` is pure: it reads sources under ``root`` and returns the files
that ``sync`` would write, so tests and the drift check never touch the disk
beyond reading.
"""

