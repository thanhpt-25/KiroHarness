@dataclass(frozen=True)
class Planned:
    path: str
    content: str
    sources: tuple
    always_for: tuple = ()  # Agents whose Always_On_Context includes this file


@dataclass
class Plan:
    files: dict = field(default_factory=dict)  # path -> Planned
    warnings: list = field(default_factory=list)
    version: str = ""

    def add(self, planned: Planned) -> None:
        old = self.files.get(planned.path)
        if old is not None:
            if old.content != planned.content:
                raise manifest_mod.ManifestError([f"two renderers produce different content for {planned.path}"])
            merged = tuple(sorted(set(old.always_for) | set(planned.always_for)))
            planned = Planned(planned.path, planned.content, old.sources, merged)
        self.files[planned.path] = planned


@dataclass(frozen=True)
class Source:
    path: str
    text: str
    name: str
    inclusion: str
    patterns: tuple
    description: str
    body: str


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def read_sources(root, manifest) -> list:
    sources = []
    for rel in manifest_mod.guidance_files(root, manifest):
        with open(os.path.join(root, rel), encoding="utf-8", newline="") as handle:
            text = handle.read()
        split = frontmatter.split_front_matter(text)
        if split is None:
            raise manifest_mod.ManifestError([f"{rel}: guidance source needs a front matter block"])
        try:
            data = frontmatter.parse_front_matter(split[0])
        except frontmatter.FrontMatterError as exc:
            raise manifest_mod.ManifestError([f"{rel}: front matter line {exc.line}: {exc.msg}"])
        inclusion = data.get("inclusion")
        if inclusion not in ("always", "fileMatch", "auto", "manual"):
            raise manifest_mod.ManifestError([f"{rel}: inclusion must be always, fileMatch, auto or manual"])
        pattern = data.get("fileMatchPattern", [])
        patterns = tuple([pattern] if isinstance(pattern, str) else pattern)
        name = os.path.basename(rel)[: -len(".md")]
        sources.append(Source(rel, text, name, inclusion, patterns, str(data.get("description", "")), split[1]))
    return sources


def header(sources, version: str) -> str:
    names = ", ".join(sources)
    return f"<!-- Generated by scripts/harness sync from {names} (harness {version}). Do not edit by hand; edit the sources and run scripts/harness sync. -->"


def expand_braces(pattern: str) -> list:
    """Expand ``{a,b}`` groups so targets without brace support select the same paths."""
    start = pattern.find("{")
    if start < 0:
        return [pattern]
    depth, parts, current, end = 0, [], "", None
    for index in range(start, len(pattern)):
        char = pattern[index]
        if char == "{":
            depth += 1
            if depth == 1:
                continue
        elif char == "}":
            depth -= 1
            if depth == 0:
                parts.append(current)
                end = index
                break
        elif char == "," and depth == 1:
            parts.append(current)
            current = ""
            continue
        current += char
    if end is None:  # unbalanced: leave the text alone
        return [pattern]
    return [pattern[:start] + mid + tail for part in parts for tail in expand_braces(pattern[end + 1 :]) for mid in expand_braces(part)]


def expanded(patterns) -> list:
    out = []
    for pattern in patterns:
        for item in expand_braces(pattern):
            if item not in out:
                out.append(item)
    return out


def _body(source: Source) -> str:
    return source.body.strip("\n")


def _with_header(front: str, body: str, sources, version: str) -> str:
    """Front matter (may be empty) + generated header + body, LF, one trailing newline."""
    prefix = f"---\n{front}---\n\n" if front else ""
    return f"{prefix}{header(sources, version)}\n\n{body.strip(chr(10))}\n"


# ---- MCP ----------------------------------------------------------------

def mcp_servers(manifest, kiro: bool = False) -> dict:
    """Server objects with the Manifest's pins and Secret_References; Kiro adds disabled and autoApprove."""
    servers = {}
    for name in sorted(manifest["mcp"]):
        item = manifest["mcp"][name]
        server = {"command": item.get("runner", "uvx"), "args": [f"{item['package']}@{item['version']}", *item["args"]]}
        if item.get("env"):
            server["env"] = dict(item["env"])
        if kiro:
            server["disabled"] = item["disabled"]
            server["autoApprove"] = list(item["auto_approve"])
        servers[name] = server
    return servers


# ---- Kiro ---------------------------------------------------------------

def render_kiro(root, manifest, sources, plan) -> None:
    for source in sources:
        plan.add(Planned(f".kiro/steering/{source.name}.md", source.text, (source.path,), ("kiro",) if source.inclusion == "always" else ()))
    for name, (group, key) in sorted(KIRO_HOOKS.items()):
        entry = manifest[group].get(key)
        enabled = entry["enabled"] if isinstance(entry, dict) else bool(entry)
        if not enabled:
            continue
        rel = f"harness/kiro/hooks/{name}.json"
        with open(os.path.join(root, rel), "rb") as handle:
            hook = hookconfig.parse_hook_bytes(handle.read(), rel)
        plan.add(Planned(f".kiro/hooks/{name}.json", hookconfig.print_hook_file(hook), (rel,)))
    servers = mcp_servers(manifest, kiro=True)
    plan.add(Planned(".kiro/settings/mcp.json", jsonfmt.dumps({"mcpServers": servers}) + "\n", ("harness/manifest.json",)))


# ---- Portable guidance --------------------------------------------------

def _guidance_index(sources) -> str:
    lines = []
    for source in sources:
        if source.inclusion == "always":
            continue
        when = {"fileMatch": "when working on files matching " + ", ".join(f"`{p}`" for p in source.patterns),
                "auto": source.description or "when relevant", "manual": "only when asked"}[source.inclusion]
        lines.append(f"- [{source.name}]({source.path}): read {when}")
    return "\n".join(lines)


def _agents_md(sources, version) -> Planned:
    always = [s for s in sources if s.inclusion == "always"]
    parts = ["# Project guidance"] + [_body(s) for s in always]
    index = _guidance_index(sources)
    if index:
        parts += ["## Additional guidance\n\n" + index]
    used = tuple(s.path for s in always) or ("harness/guidance",)
    body = "\n\n".join(parts)
    return Planned("AGENTS.md", f"{header(used, version)}\n\n{body}\n", used, ("claude-code", "cursor", "copilot", "codex"))


def _capabilities(root) -> dict:
    try:
        with open(os.path.join(root, "harness/capabilities.json"), encoding="utf-8") as handle:
            return json.load(handle)["agents"]["claude-code"]
    except (OSError, ValueError, KeyError) as exc:
        raise manifest_mod.ManifestError([f"harness/capabilities.json has no usable claude-code entry: {exc}"])


def _guard_command(trigger: str, keys) -> str:
    only = ""
    if len(keys) != len(PRE_TOOL_GUARDS if trigger == "pre_tool" else ("prompt_secrets",)):
        only = " --only " + ",".join(GUARD_NAMES[k] for k in keys)
    return f'"$CLAUDE_PROJECT_DIR"/harness/bin/guard claude-code {trigger}{only}'


def render_claude_native(root, manifest, plan) -> None:
    """``.claude/settings.json`` (hooks, permissions) and ``.mcp.json`` (agent-harness-platform R8.1 to R8.3)."""
    entry = _capabilities(root)
    hooks: dict = {}
    pre = [k for k in PRE_TOOL_GUARDS if manifest["guards"].get(k, {}).get("enabled")]
    if pre:
        tools = sorted(entry["tool_map"]) + [prefix + ".*" for prefix in sorted(entry["tool_prefix_map"])]
        hooks["PreToolUse"] = [{"matcher": "^(" + "|".join(tools) + ")$",
                                "hooks": [{"type": "command", "command": _guard_command("pre_tool", pre), "timeout": 5}]}]
    if manifest["guards"].get("prompt_secrets", {}).get("enabled"):
        hooks["UserPromptSubmit"] = [{"hooks": [{"type": "command", "command": _guard_command("prompt_submit", ["prompt_secrets"]), "timeout": 5}]}]
    if manifest["quality"].get("session_start"):
        hooks["SessionStart"] = [{"hooks": [{"type": "command", "command": '"$CLAUDE_PROJECT_DIR"/harness/bin/session-start', "timeout": 10}]}]
    if manifest["quality"].get("stop_validate"):
        hooks["Stop"] = [{"hooks": [{"type": "command", "command": '"$CLAUDE_PROJECT_DIR"/harness/bin/stop-validate', "timeout": 300}]}]
    rules = permissions.derive(root, entry, manifest["mcp"])
    for item in rules["skipped"]:
        plan.warnings.append(f"claude-code: no permission rule for {item}; the hook is the only layer")
    settings = {"permissions": {"allow": rules["allow"], "ask": rules["ask"], "deny": rules["deny"]}, "hooks": hooks}
    disabled = sorted(name for name, item in manifest["mcp"].items() if item["disabled"])
    if disabled:
        settings["disabledMcpjsonServers"] = disabled
    sources = ("harness/manifest.json", "harness/policy/destructive-commands.txt", "harness/policy/risky-tools.conf", "harness/capabilities.json")
    plan.add(Planned(".claude/settings.json", jsonfmt.dumps(settings) + "\n", sources))
    plan.add(Planned(".mcp.json", jsonfmt.dumps({"mcpServers": mcp_servers(manifest)}) + "\n", ("harness/manifest.json",)))


def render_claude(root, manifest, sources, plan) -> None:
    render_claude_native(root, manifest, plan)
    agent = manifest["agents"]["claude-code"]
    maintainer, used = "", ["harness/guidance"]
    if agent.get("maintainer"):
        with open(os.path.join(root, agent["maintainer"]), encoding="utf-8") as handle:
            maintainer = "\n\n" + handle.read().strip("\n")
        used = [agent["maintainer"]]
    plan.add(Planned("CLAUDE.md", f"{header(used, plan.version)}\n\n@AGENTS.md{maintainer}\n", tuple(used), ("claude-code",)))
    for source in sources:
        if source.inclusion == "fileMatch":
            front = "paths:\n" + "".join(f'  - "{p}"\n' for p in expanded(source.patterns))
        elif source.inclusion == "auto":
            front = ""
            plan.warnings.append(f"claude-code: guidance '{source.name}' uses inclusion 'auto'; Claude Code rules cannot load by description, so it loads every session (fallback)")
        else:
            continue
        plan.add(Planned(f".claude/rules/{source.name}.md", _with_header(front, _body(source), (source.path,), plan.version), (source.path,),
                         ("claude-code",) if not front else ()))


def render_cursor(root, manifest, sources, plan) -> None:
    for source in sources:
        lines = []
        if source.description:
            lines.append(f"description: {json.dumps(source.description)}\n")
        if source.inclusion == "fileMatch":
            lines.append("globs: " + ", ".join(expanded(source.patterns)) + "\n")
        lines.append(f"alwaysApply: {'true' if source.inclusion == 'always' else 'false'}\n")
        plan.add(Planned(f".cursor/rules/{source.name}.mdc", _with_header("".join(lines), _body(source), (source.path,), plan.version),
                         (source.path,), ("cursor",) if source.inclusion == "always" else ()))


def render_copilot(root, manifest, sources, plan) -> None:
    always = [s for s in sources if s.inclusion == "always"]
    parts = [_body(s) for s in always]
    index = _guidance_index([s for s in sources if s.inclusion in ("manual",)])
    if index:
        parts.append("## Additional guidance\n\n" + index)
    used = tuple(s.path for s in always) or ("harness/guidance",)
    plan.add(Planned(".github/copilot-instructions.md", f"{header(used, plan.version)}\n\n" + "\n\n".join(parts) + "\n", used, ("copilot",)))
    for source in sources:
        if source.inclusion == "fileMatch":
            apply_to = ",".join(expanded(source.patterns))
        elif source.inclusion == "auto":
            apply_to = "**"
            plan.warnings.append(f"copilot: guidance '{source.name}' uses inclusion 'auto'; Copilot instructions cannot load by description, so it applies to every file (fallback)")
        else:
            continue
        plan.add(Planned(f".github/instructions/{source.name}.instructions.md",
                         _with_header(f'applyTo: "{apply_to}"\n', _body(source), (source.path,), plan.version), (source.path,), ()))


RENDERERS = {"kiro": render_kiro, "claude-code": render_claude, "cursor": render_cursor, "copilot": render_copilot}


def build_plan(root, manifest=None) -> Plan:
    manifest = manifest or manifest_mod.load(root)
    plan = Plan(version=manifest["harness_version"])
    sources = read_sources(root, manifest)
    enabled = [a for a, v in manifest["agents"].items() if v["enabled"]]
    for agent in enabled:
        if agent in UNVERIFIED:
            plan.warnings.append(f"{agent}: output format is not verified against vendor documentation yet (see docs/adr/0007-generator-design.md)")
        if agent == "kiro":
            render_kiro(root, manifest, sources, plan)
        else:
            RENDERERS[agent](root, manifest, sources, plan)
    render_capabilities_doc(root, plan)
    if manifest.get("agents_md") or any(a != "kiro" for a in enabled):
        plan.add(_agents_md(sources, plan.version))
    return plan


FILES_BY_AGENT = {
    "kiro": ".kiro/steering/, .kiro/hooks/ (shipped hooks), .kiro/settings/mcp.json",
    "claude-code": "AGENTS.md, CLAUDE.md, .claude/rules/, .claude/settings.json, .mcp.json",
    "cursor": ".cursor/rules/*.mdc (and AGENTS.md)",
    "copilot": ".github/copilot-instructions.md, .github/instructions/ (and AGENTS.md)",
}
GUARD_COLUMNS = (("destructive", "Destructive command guard"), ("risky", "Risky tool guard"), ("prompt_secrets", "Prompt secret scan"))


def render_capabilities_doc(root, plan) -> None:
    """``docs/reference/capabilities.md``: protection level per Agent and guard, from the matrix (R9.1, R9.3)."""
    with open(os.path.join(root, "harness/capabilities.json"), encoding="utf-8") as handle:
        agents = json.load(handle)["agents"]
    lines = ["# Capability matrix", "",
             "Which protections each Agent gets. Levels: **enforced** (a hook blocks or asks), **permission-only** (the Agent's own permission rules, no hook), **guidance-only** (the rule is text the Agent may ignore). `documented` means the contract was read from vendor documentation; it becomes `verified` only after a Manual_Check_Record exists under `docs/verification/`.", "",
             "| Agent | Status | " + " | ".join(label for _k, label in GUARD_COLUMNS) + " |",
             "|---|---|" + "---|" * len(GUARD_COLUMNS)]
    for name, entry in sorted(agents.items()):
        levels = " | ".join(entry.get("protection", {}).get(key, "n/a") for key, _l in GUARD_COLUMNS)
        lines.append(f"| {entry['label']} | {entry['status']} | {levels} |")
    lines += ["", "## Files the Generator writes", ""]
    for name, entry in sorted(agents.items()):
        lines.append(f"- {entry['label']}: {FILES_BY_AGENT.get(name, 'none')}")
    lines += ["", "## Known gaps", ""]
    for name, entry in sorted(agents.items()):
        for gap in entry.get("gaps", []):
            lines.append(f"- {entry['label']}: {gap}")
    lines += ["", "## Verification", ""]
    for name, entry in sorted(agents.items()):
        verified = entry.get("verified", {})
        lines.append(f"- {entry['label']}: {verified.get('source', 'no source recorded')} ({verified.get('date', 'no date')})")
    text = header(("harness/capabilities.json",), plan.version) + "\n\n" + "\n".join(lines) + "\n"
    plan.add(Planned("docs/reference/capabilities.md", text, ("harness/capabilities.json",)))


def lock_text(plan: Plan) -> str:
    files = {p: {"sha256": sha256(f.content), "sources": list(f.sources)} for p, f in sorted(plan.files.items())}
    return jsonfmt.dumps({"schema": 1, "harness_version": plan.version, "files": files}) + "\n"


def always_on_sizes(plan: Plan) -> dict:
    """Agent -> (lines, characters) of its Always_On_Context."""
    sizes: dict = {}
    for planned in plan.files.values():
        for agent in planned.always_for:
            text = planned.content
            lines, chars = sizes.get(agent, (0, 0))
            sizes[agent] = (lines + text.count("\n"), chars + len(text))
    return sizes
